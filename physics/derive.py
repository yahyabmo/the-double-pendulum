"""
Symbolic derivation of the double pendulum's equations of motion.

This is the physics "source of truth" for Chaos Lab. It follows the same
Lagrangian approach as the original script (legacy/double pendulum.py), adds
viscous damping at each joint as a generalized force, solves the
Euler-Lagrange equations for the angular accelerations, and emits optimized
TypeScript (common-subexpression eliminated) into src/physics/generated.ts.

Run:  python3 physics/derive.py      (or: npm run derive)
"""

from pathlib import Path

import sympy as smp
from sympy.printing.jscode import JavascriptCodePrinter

# --- Symbols ---------------------------------------------------------------
t, g = smp.symbols("t g")
m1, m2 = smp.symbols("m1 m2", positive=True)
L1, L2 = smp.symbols("L1 L2", positive=True)
b = smp.symbols("b", nonnegative=True)  # joint damping coefficient

the1 = smp.Function("theta1")(t)
the2 = smp.Function("theta2")(t)
the1_d, the2_d = the1.diff(t), the2.diff(t)
the1_dd, the2_dd = the1_d.diff(t), the2_d.diff(t)

# --- Kinematics (pivot at origin, y up) -------------------------------------
x1 = L1 * smp.sin(the1)
y1 = -L1 * smp.cos(the1)
x2 = x1 + L2 * smp.sin(the2)
y2 = y1 - L2 * smp.cos(the2)

# --- Energies & Lagrangian ---------------------------------------------------
T = smp.Rational(1, 2) * m1 * (x1.diff(t) ** 2 + y1.diff(t) ** 2) + smp.Rational(
    1, 2
) * m2 * (x2.diff(t) ** 2 + y2.diff(t) ** 2)
V = m1 * g * y1 + m2 * g * y2
L = T - V

# Generalized damping forces: each joint resists its own relative rotation.
# Joint 1 (pivot) sees theta1_dot, joint 2 (elbow) sees (theta2_dot - theta1_dot).
Q1 = -b * the1_d + b * (the2_d - the1_d)
Q2 = -b * (the2_d - the1_d)

# Euler-Lagrange: d/dt(dL/dq') - dL/dq = Q
LE1 = (L.diff(the1_d)).diff(t) - L.diff(the1) - Q1
LE2 = (L.diff(the2_d)).diff(t) - L.diff(the2) - Q2

# The equations are linear in the accelerations:  M(q) * q'' = f(q, q').
# Solve the 2x2 system with Cramer's rule (fast, and keeps expressions compact).
M, f = smp.linear_eq_to_matrix(
    [smp.expand(LE1), smp.expand(LE2)], [the1_dd, the2_dd]
)

# --- Replace functions of time with plain symbols for code generation -------
th1, th2, w1, w2 = smp.symbols("th1 th2 w1 w2")


def plain(expr):
    expr = expr.subs({the1_d: w1, the2_d: w2}).subs({the1: th1, the2: th2})
    return smp.trigsimp(smp.factor_terms(smp.expand_trig(expr)))


M = M.applyfunc(plain)
f = f.applyfunc(plain)
det = smp.factor(smp.trigsimp(M[0, 0] * M[1, 1] - M[0, 1] * M[1, 0]))
a1 = (f[0] * M[1, 1] - M[0, 1] * f[1]) / det
a2 = (M[0, 0] * f[1] - f[0] * M[1, 0]) / det
KE = plain(T)
PE = plain(V)


# --- Emit TypeScript ----------------------------------------------------------
class TSPrinter(JavascriptCodePrinter):
    def _print_Pow(self, expr):
        base, exp = expr.as_base_exp()
        if exp == 2:
            b_ = self.parenthesize(base, 100)
            return f"{b_}*{b_}"
        if exp == -1:
            return f"1/{self.parenthesize(base, 100)}"
        if exp == -2:
            b_ = self.parenthesize(base, 100)
            return f"1/({b_}*{b_})"
        return super()._print_Pow(expr)


printer = TSPrinter()


def emit(name, exprs, outs, doc):
    repl, reduced = smp.cse(exprs, symbols=smp.numbered_symbols("x"))
    lines = [f"/** {doc} */"]
    args = "th1: number, th2: number, w1: number, w2: number, g: number, m1: number, m2: number, L1: number, L2: number"
    if outs:
        lines.append(f"export function {name}(out: Float64Array, {args}, b: number): void {{")
    else:
        lines.append(f"export function {name}({args}): number {{")
    for sym, e in repl:
        lines.append(f"  const {sym} = {printer.doprint(e)};")
    if outs:
        for i, e in enumerate(reduced):
            lines.append(f"  out[{i}] = {printer.doprint(e)};")
    else:
        lines.append(f"  return {printer.doprint(reduced[0])};")
    lines.append("}")
    return "\n".join(lines)


header = """// AUTO-GENERATED by physics/derive.py — do not edit by hand.
// Regenerate with: npm run derive
/* eslint-disable */
"""

body = "\n\n".join(
    [
        emit(
            "accelerations",
            [a1, a2],
            True,
            "Angular accelerations [theta1'', theta2''] from the Euler-Lagrange equations (with joint damping b).",
        ),
        emit("kineticEnergy", [KE], False, "Kinetic energy T."),
        emit("potentialEnergy", [PE], False, "Potential energy V (zero at pivot height)."),
    ]
)

# Unused params are expected in some functions (e.g. g in kineticEnergy).
ts = header + "// @ts-nocheck — generated code may leave parameters unused\n\n" + body + "\n"

out = Path(__file__).resolve().parent.parent / "src" / "physics" / "generated.ts"
out.write_text(ts)
print(f"wrote {out}")
print("theta1'' =", a1)
print("theta2'' =", a2)
